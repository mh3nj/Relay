import { DEFAULT_ALPHABET } from "@/lib/morse";

export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

export function downloadText(content: string, filename: string) {
  downloadBlob(new Blob([content], { type: "text/plain;charset=utf-8" }), filename);
}

export function downloadJson(data: unknown, filename: string) {
  downloadBlob(
    new Blob([JSON.stringify(data, null, 2)], { type: "application/json" }),
    filename
  );
}

export interface TranslationExport {
  plainText: string;
  morse: string;
  wpm: number;
  frequency: number;
  exportedAt: string;
}

export function buildTranslationExport(
  plainText: string,
  morse: string,
  wpm: number,
  frequency: number
): TranslationExport {
  return { plainText, morse, wpm, frequency, exportedAt: new Date().toISOString() };
}

/** Generate a printable Morse code reference sheet (letters, numbers,
 * punctuation) as a downloadable PDF. jsPDF is loaded on demand so it
 * doesn't inflate the initial app bundle for people who never export a
 * PDF. */
export async function downloadMorseReferencePdf() {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const marginX = 48;
  let y = 56;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.text("Morse Code Reference", marginX, y);
  y += 28;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(90);
  doc.text("Generated by Relay. Free, offline, privacy-first.", marginX, y);
  y += 24;
  doc.setTextColor(20);

  const columns = 4;
  const colWidth = (595 - marginX * 2) / columns;
  const rowHeight = 22;
  let col = 0;
  let rowStartY = y;

  doc.setFontSize(11);
  DEFAULT_ALPHABET.forEach((symbol, i) => {
    const x = marginX + col * colWidth;
    doc.setFont("helvetica", "bold");
    doc.text(symbol.char, x, rowStartY);
    doc.setFont("courier", "normal");
    doc.text(symbol.code, x + 24, rowStartY);

    col++;
    if (col >= columns) {
      col = 0;
      rowStartY += rowHeight;
    }
    if (rowStartY > 780 && i < DEFAULT_ALPHABET.length - 1) {
      doc.addPage();
      rowStartY = 56;
    }
  });

  doc.save("morse-code-reference.pdf");
}
